#!/usr/bin/env node
// Emits dist/client/_redirects for the locale-less entry paths.
//
// Why this exists: with i18n `prefixDefaultLocale: true`, Astro's router answers 404 for
// SSR routes that carry no locale prefix, so `/about/`, `/blog/`, `/search/` and
// `/blog/<slug>/` cannot be served by page components. Astro 5 hid this by prerendering
// those pages into meta-refresh HTML; under Workers static assets a prerendered
// `Astro.redirect()` emits an empty 200 file instead, which is worse than the bug.
//
// Cloudflare serves _redirects at the edge with real 308s and no Worker invocation.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CACHE_FILE = path.join(ROOT, "src/lib/.cache/post-summaries.json");
const OUT_FILE = path.join(ROOT, "dist/client/_redirects");
const DEFAULT_LOCALE = "ua";
// Locale priority when the same slug exists in more than one language.
const LOCALE_ORDER = ["ua", "ru", "en"];

async function main() {
  const summaries = JSON.parse(await readFile(CACHE_FILE, "utf8"));

  const localeBySlug = new Map();
  for (const summary of summaries) {
    const current = localeBySlug.get(summary.slug);
    if (current === undefined || LOCALE_ORDER.indexOf(summary.locale) < LOCALE_ORDER.indexOf(current)) {
      localeBySlug.set(summary.slug, summary.locale);
    }
  }

  const lines = [
    "# Generated by scripts/build-redirects.mjs - do not edit by hand.",
    `/about/ /${DEFAULT_LOCALE}/about/ 308`,
    `/blog/ /${DEFAULT_LOCALE}/blog/ 308`,
    `/search/ /${DEFAULT_LOCALE}/search/ 308`,
  ];

  for (const [slug, locale] of [...localeBySlug].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`/blog/${slug}/ /${locale}/blog/${slug}/ 308`);
  }

  await writeFile(OUT_FILE, `${lines.join("\n")}\n`);
  console.log(`[redirects] Wrote ${lines.length - 1} rules to ${path.relative(ROOT, OUT_FILE)}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
