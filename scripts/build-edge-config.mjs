#!/usr/bin/env node
// Writes the two Cloudflare edge-config files into the built asset directory (dist/client):
//
//   _redirects  - locale-less section landing pages -> default-locale version
//   _headers    - security headers on every response (the adapter only pre-fills
//                 immutable Cache-Control for /_astro/*, so we append the rest)
//
// WHY _headers matters here: under Workers static assets, prerendered pages are served
// straight from the CDN WITHOUT running src/middleware.ts, so the middleware's security
// headers never reach them. This file is what protects the bulk of the site. Values are
// read from src/config/security-headers.json so middleware (SSR) and _headers (static)
// stay identical.
import { readFile, writeFile, appendFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CLIENT_DIR = path.join(ROOT, "dist/client");
const HEADERS_JSON = path.join(ROOT, "src/config/security-headers.json");
const LEGACY_JSON = path.join(ROOT, "src/config/legacy-redirects.json");
const DEFAULT_LOCALE = "ua";

// Locale-less section entry points. Astro's i18n (prefixDefaultLocale) 404s these without
// a prefix, so they are redirected here at the edge. Per-post `/blog/<slug>/` URLs are NOT
// generated: they never existed under the old build.
const SECTION_REDIRECTS = [
  ["/about/", `/${DEFAULT_LOCALE}/about/`],
  ["/blog/", `/${DEFAULT_LOCALE}/blog/`],
  ["/search/", `/${DEFAULT_LOCALE}/search/`],
];

async function writeRedirects() {
  // Legacy dead URLs must be redirected at the edge, not in middleware: under Workers
  // static assets, middleware does not run for paths matching no route, so those redirects
  // would silently 404. _redirects runs before the Worker for every request.
  const legacy = JSON.parse(await readFile(LEGACY_JSON, "utf8"));
  const lines = [
    "# Generated by scripts/build-edge-config.mjs - do not edit by hand.",
    ...SECTION_REDIRECTS.map(([from, to]) => `${from} ${to} 308`),
    ...legacy.map(([from, to]) => `${from} ${to} 308`),
  ];
  await writeFile(path.join(CLIENT_DIR, "_redirects"), `${lines.join("\n")}\n`);
  return lines.length - 1;
}

async function appendSecurityHeaders() {
  const headers = JSON.parse(await readFile(HEADERS_JSON, "utf8"));
  const block = [
    "",
    "# Security headers (source: src/config/security-headers.json) - applied to every",
    "# response, since static assets bypass src/middleware.ts under Workers.",
    "/*",
    ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`),
    "",
  ];
  await appendFile(path.join(CLIENT_DIR, "_headers"), block.join("\n"));
  return Object.keys(headers).length;
}

async function main() {
  const redirectCount = await writeRedirects();
  const headerCount = await appendSecurityHeaders();
  console.log(`[edge] Wrote ${redirectCount} redirect rules and ${headerCount} security headers.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
